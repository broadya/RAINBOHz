"""Emits a canonical model as the Cypher script `rendering-engine --state` loads.

The output follows the hand-written examples in `engine-db/examples/`: the
`EngineConfig` in a statement of its own, then the whole score in one
statement, every node and relationship a pattern referring to the others by
variable. Nothing is looked up with `MATCH`, so loading needs no index and
performs no scan.

The score is one `CREATE` clause with comma-separated patterns, not one
`CREATE` clause per pattern. The two are equivalent Cypher, but Ladybug
(fork of 0.19.1) crashed with SIGBUS on a statement of 493 `CREATE` clauses,
while the same 493 patterns in one clause load, transform and render; the
depth of the per-clause binding is the likely cause. Established by
experiment on 2026-10-02 with `examples/demo`.
"""

from __future__ import annotations

from collections.abc import Iterable
from decimal import Decimal
from typing import Any

from .model import TABLE_ORDER, EngineConfigRow, Model


def literal(value: Any) -> str:
    """Formats one property value as a Cypher literal.

    Floats are written in fixed notation from their shortest round-trip
    representation, with a decimal point always present, so that a FLOAT
    column never receives an integer literal and no exponent notation is
    relied on. Integers and booleans are written as such; strings are quoted
    with backslash and double quote escaped.

    Raises:
        TypeError: for a value of any other type.
    """
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        text = format(Decimal(repr(value)), "f")
        return text if "." in text else text + ".0"
    if isinstance(value, str):
        escaped = value.replace("\\", "\\\\").replace('"', '\\"')
        return f'"{escaped}"'
    raise TypeError(f"no Cypher literal for {type(value).__name__}")


def properties(values: dict[str, Any]) -> str:
    """Formats a property map as ` {k: v, ...}`, or nothing when empty."""
    if not values:
        return ""
    return " {" + ", ".join(f"{key}: {literal(value)}" for key, value in values.items()) + "}"


def emit_cypher(model: Model, comment_lines: Iterable[str] = ()) -> str:
    """Serialises `model` as a Cypher script.

    Args:
        model: The compiled score.
        comment_lines: Lines for the header comment, after the generator's
            own, without the `//` prefix.

    Returns:
        The script text: a header comment, the `EngineConfig` statement, then
        the score as one statement, nodes by table then edges by relationship.
    """
    out: list[str] = []
    out.append("// " + "=" * 60)
    out.append("// Generated by hzlc. Do not edit: edit the HzL source and recompile.")
    for line in comment_lines:
        out.append(f"// {line}".rstrip())
    out.append("// " + "=" * 60)
    out.append("")

    config = model.rows[EngineConfigRow.TABLE]
    if config:
        out.append("// Engine configuration, from compiler options; not part of the score.")
        for index, row in enumerate(config):
            variable = EngineConfigRow.TABLE[0].lower() + EngineConfigRow.TABLE[1:] + str(index)
            out.append(f"CREATE ({variable}:{row.TABLE}{properties(row.properties())});")
        out.append("")

    # Every pattern of the score, with the comment that heads its group.
    # Patterns are joined into one clause below; comments are whitespace to
    # the Cypher lexer, so they can sit between patterns.
    lines: list[str] = []
    for table in TABLE_ORDER:
        if table == EngineConfigRow.TABLE:
            continue
        rows = model.rows[table]
        if not rows:
            continue
        lines.append(f"// {table}: {len(rows)}")
        for index, row in enumerate(rows):
            variable = table[0].lower() + table[1:] + str(index)
            lines.append(f"({variable}:{table}{properties(row.properties())})")

    by_rel: dict[str, list[str]] = {}
    for edge in model.edges:
        pattern = (
            f"({edge.src.variable})-[:{edge.rel}{properties(edge.properties)}]"
            f"->({edge.dst.variable})"
        )
        by_rel.setdefault(edge.rel, []).append(pattern)
    for rel, patterns in by_rel.items():
        lines.append(f"// {rel}: {len(patterns)}")
        lines.extend(patterns)

    patterns_left = sum(1 for line in lines if not line.startswith("//"))
    first = True
    for line in lines:
        if line.startswith("//"):
            out.append(line)
            continue
        patterns_left -= 1
        prefix = "CREATE " if first else "       "
        first = False
        out.append(prefix + line + ("," if patterns_left else ";"))
    out.append("")
    return "\n".join(out)
